local time = Time.GetRealTimeMs()



local function toVector(str)
    local c = {}
    for n in string.gmatch(str, "-?%d+%.?%d*") do c[#c + 1] = basicModule.tonumber(n) end
    if #c < 2 or #c > 4 then return false end
    local class = _G["Vector" .. #c]
    return class and class.new(table.unpack(c)) or false
end



function OnGet(args, getTime)
    Debug.log("get " .. #args .. " objs at " .. getTime)
    for i = 1, #args do
        Debug.log("  " .. i .. ": " .. basicModule.tostring(args[i]))
    end
end

function Send(args)
    local argsforjson = {}
    for i, data in tableIterators.pairs(args) do
        argsforjson["args" .. i - 1] = basicModule.tostring(data)
    end

    local newTable = {
        Type = "POST",
        Time = basicModule.tostring(Time.GetRealTimeMs()),
        data = argsforjson
    }

    local resultJson = json.serialize(newTable)

    Debug.log("post " .. resultJson)
    File.SetPlayerPrefsStr("WEB", resultJson)
end



Send({ "привет", Vector3.New(1, 2, 3) })

local prevprefs = ""
function Update()
    time = Time.GetRealTimeMs()
    local curprefs = File.GetPlayerPrefsStr("WEB", nil)
    if curprefs ~= nil and curprefs ~= prevprefs then
        prevprefs = curprefs
        local table = json.parse(prevprefs)
        local argsraw = table.data
        local getTime = table.Time

        local args = {}

        local counter = 0
        for i, data in tableIterators.pairs(argsraw) do
            counter = counter + 1
            local result = nil
            data = string.gsub(data, '"', "")
            local numdata = basicModule.tonumber(data)
            if numdata ~= nil then
                result = numdata
            end

            if not result then
                result = toVector(data)
            end

            if not result then
                result = data
            end

            args[counter] = result
        end

        OnGet(args, getTime)
    end
end
